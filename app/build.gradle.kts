// Release signing: keystore.properties (git-ignored) points at a keystore outside the repo.
// Keep the same keystore forever: updates only install over the old app (and keep the pairing) when signed with it.
val keystoreProps = Properties().apply {
    val f = rootProject.file("keystore.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}

android {
    namespace = "com.samvedamanikam.sam"
    compileSdk = 37

    defaultConfig {
        applicationId = "com.samvedamanikam.sam"
        minSdk = 26
        targetSdk = 37
        versionCode = 1
        versionName = "0.3.0"
        buildConfigField("String", "DEFAULT_BASE_URL", "\"https://samvedamanikam.com/\"")
        buildConfigField("String", "DEVICE_AUTH_APP", "\"sam\"")
    }

    signingConfigs {
        if (keystoreProps.isNotEmpty()) {
            create("release") {
                storeFile = file(keystoreProps.getProperty("storeFile"))
                storePassword = keystoreProps.getProperty("storePassword")
                keyAlias = keystoreProps.getProperty("keyAlias")
                keyPassword = keystoreProps.getProperty("keyPassword")
            }
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
            signingConfigs.findByName("release")?.let { signingConfig = it }
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    buildFeatures {
        compose = true
        buildConfig = true
    }
}

base.archivesName.set("SAM-${android.defaultConfig.versionName}")

